function paras(paperId: string, page: number, start: number, texts: string[]): Chunk[] {
  return texts.map((text, i) => ({
    id: `${paperId}-p${page}-${start + i}`,
    paper_id: paperId,
    page,
    para_index: start + i,
    text,
  }))
}

